#!/usr/bin/env python3
"""Capture retail 7AD6 joystick fallback with host-normalised axis calibration."""
import argparse
import hashlib
from pathlib import Path
import random
import struct
import sys
from generate_resource_directory import IMAGE_SHA256


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('workspace', type=Path)
    args = parser.parse_args()
    sys.path.insert(0, str(args.workspace.resolve() / 'tools'))
    from trace_hidden_commands import Harness
    image = (args.workspace / 'analysis/unpacked/image.bin').read_bytes()
    if hashlib.sha256(image).hexdigest() != IMAGE_SHA256:
        raise ValueError('Unsupported unpacked executable')
    rng = random.Random(0x7bca)
    cases = []
    for sequence in range(8):
        h = Harness(image)
        def word(at, value):
            h.write(at, struct.pack('<H', value & 65535))
        h.write(0x3b52, b'\0')
        h.write(0x1749, b'\3')
        h.write(0x15aa, b'\0')
        for at in (0x15b0, 0x11da, 0x11dc, 0x7aef, 0x7afe, 0x7b49, 0x7b64, 0x7b4c, 0x7b67, 0x7b97, 0x7bae):
            word(at, 0)
        word(0x17b0, 32767)
        for tick in range(32):
            x, y = (rng.randrange(-32767, 32768) for _ in range(2))
            if sequence == 0:
                x = (0, 2047, 2048, 4096, 32767, -32767, -4096, 0)[tick % 8]
                y = -x
            step = rng.choice((1, 8, 16, 32, 100))
            word(0x1714, x)
            word(0x1716, y)
            h.setreg('CX', step)
            h.cpu.ctl_remove_cache(h.BASE, h.BASE + 65536)
            h.call(0x7ad6)
            references = [int.from_bytes(h.read(at, 2), 'little') for at in (0xd62d, 0xd5ca)]
            cases.append((sequence, x, y, step, h.getreg('AX'), h.getreg('DX'), *references))
    lines = ['#pragma once', '', '// Retail 7AD6 joystick fallback; generated by tools/generate_joystick_reference.py.',
             '// Image SHA-256: ' + IMAGE_SHA256, '#include <array>', '', 'namespace darker::test_reference {',
             'inline constexpr std::array<std::array<int, 8>, 256> joystick_samples{{']
    lines += ['  {' + ', '.join(map(str, case)) + '},' for case in cases]
    lines += ['}};', '} // namespace darker::test_reference', '']
    (Path(__file__).resolve().parents[1] / 'tests/reference/joystick_samples.h').write_text('\n'.join(lines))
    print(f'Captured {len(cases)} retail joystick updates.')


if __name__ == '__main__':
    main()
